/**
 * app/result.js — facts about the finished DFA: the full transition table,
 * the "About this diagram" card, the summary pills, and the text export.
 */
(function () {
  'use strict';
  const { $, esc } = App;
  const A = window.Automata;

  const LEGEND = `<div class="legend">
    <span><svg viewBox="0 0 26 18"><path d="M1 9h14"/><path d="M12 5l4 4-4 4"/><circle cx="21" cy="9" r="4"/></svg>start</span>
    <span><svg viewBox="0 0 26 18"><circle cx="13" cy="9" r="7"/><circle cx="13" cy="9" r="4"/></svg>accepting</span>
    <span><svg viewBox="0 0 26 18"><circle cx="13" cy="9" r="7" stroke-dasharray="3 2"/></svg>dead state ∅</span>
    <span><svg viewBox="0 0 26 18"><circle class="sw-hl" cx="13" cy="9" r="7"/></svg>being worked on</span>
  </div>`;

  function renderInfo() {
    const { nfa, dfa, labels } = App.s;
    if (!dfa) return;
    const max = Math.pow(2, nfa.states.length);
    const nfaFinals = new Set(nfa.finals);
    const hasDead = dfa.states.includes(A.DEAD);
    const real = dfa.states.length - (hasDead ? 1 : 0);
    const acc = dfa.finals.map(f => `${labels[f]} = ${f}`).join(', ') || 'none, so the language is empty';
    const finalsInside = [...new Set(dfa.finals.flatMap(f => dfa.sets[f].filter(s => nfaFinals.has(s))))];

    $('dfaInfo').innerHTML = `<dl>
        <dt>States</dt><dd>${dfa.states.length}${hasDead ? ` (${real} + dead state ∅)` : ''}, out of ${max} possible subsets</dd>
        <dt>Start</dt><dd>${esc(labels[dfa.start])} = ${esc(dfa.start)}, the ε-closure of ${esc(nfa.start)}</dd>
        <dt>Accepting</dt><dd>${esc(acc)}</dd>
        <dt>Moves</dt><dd>exactly one per symbol from every state (${dfa.states.length} × ${dfa.alphabet.length} = ${dfa.states.length * dfa.alphabet.length})</dd>
      </dl>
      <p class="why">Each letter stands for a set of NFA states, written under the circle. A DFA state accepts when its set contains an accepting NFA state${finalsInside.length ? ` (here ${esc(finalsInside.join(', '))})` : ''}.${hasDead ? ' ∅ catches every input the NFA has no move for, so the DFA never gets stuck.' : ''}</p>
      ${LEGEND}`;

    $('dfaTable').innerHTML = App.dfaTableHTML() +
      '<p class="hint">→ start state, * accepting state, ∅ dead state. Each letter stands for the set of NFA states beside it.</p>';

    $('dfaSummary').innerHTML =
      `<span class="pill">${nfa.states.length} NFA states became ${dfa.states.length} DFA states</span>` +
      `<span class="pill">accepting: ${esc(dfa.finals.map(f => labels[f]).join(', ') || 'none')}</span>`;
  }

  /** The DFA in the same text format as the input (so it can be re-loaded). */
  function dfaText() {
    const { dfa, labels } = App.s;
    return [
      '// DFA generated by the ε-NFA to DFA simulator (subset construction)',
      ...dfa.states.map(s => `// ${labels[s]} = ${s}`),
      `states: ${dfa.states.map(s => labels[s]).join(' ')}`,
      `alphabet: ${dfa.alphabet.join(' ')}`,
      `start: ${labels[dfa.start]}`,
      `final: ${dfa.finals.map(s => labels[s]).join(' ')}`,
      ...dfa.states.flatMap(s => dfa.alphabet.map(a => `${labels[s]} ${a} ${labels[dfa.delta[s][a]]}`)),
    ].join('\n');
  }

  function exportDFA() {
    if (!App.s.dfa) return;
    const blob = new Blob([dfaText()], { type: 'text/plain' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'dfa.txt';
    a.click();
    URL.revokeObjectURL(a.href);
  }

  App.on('init', () => { $('exportBtn').addEventListener('click', exportDFA); });
  App.on('converted', renderInfo);
  App.on('reset', () => { $('dfaInfo').innerHTML = ''; $('dfaSummary').innerHTML = ''; $('dfaTable').innerHTML = ''; });

  Object.assign(App, { renderInfo, dfaText });
})();
